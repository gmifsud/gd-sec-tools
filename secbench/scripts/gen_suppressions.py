#!/usr/bin/env python3
"""
gen_suppressions.py — derive tool-native suppression files from the single source of truth (suppressions.toml).

Emits into <out_dir>/ (per run, never into the scanned repository):
  .trivyignore.yaml      vuln_id entries (Trivy supports expired_at + statement natively)
  vex.openvex.json       OpenVEX for Trivy --vex (vuln_id [+ purl])
  vex.cdx.json           CycloneDX VEX for Dependency-Track POST /api/v1/vex
  .gitleaksignore        fingerprint entries for tool=gitleaks (gitleaks fingerprint format in match.fingerprint)
  opengrep-excludes.txt  path entries for tool=opengrep (→ --exclude args)
  zap-ignore.conf        zap_rule entries (→ appended IGNORE rows)

Expired entries are NOT emitted. generate() returns the list of active (non-expired) entries for the SARIF
normaliser, which annotates matching results with result.suppressions[] (fingerprint / rule_id / path selectors).
"""
from __future__ import annotations

import datetime as dt
import json
import sys
import tomllib
from pathlib import Path

VEX_STATUS = {  # secbench status → OpenVEX status / CycloneDX analysis.state
    "not_affected": ("not_affected", "not_affected"),
    "false_positive": ("not_affected", "false_positive"),
    "accepted_risk": ("affected", "exploitable"),   # DT: exploitable + response will_not_fix, tracked by ticket
    "fixed_elsewhere": ("fixed", "resolved"),
}


def generate(path: Path, out_dir: Path, today: dt.date | None = None) -> list[dict]:
    today = today or dt.date.today()
    out_dir.mkdir(parents=True, exist_ok=True)
    entries: list[dict] = []
    if Path(path).exists():
        with open(path, "rb") as fh:
            entries = tomllib.load(fh).get("entries", [])
    active = [e for e in entries if isinstance(e.get("expires"), dt.date) and e["expires"] >= today]

    trivy_lines = ["# GENERATED by gen_suppressions.py — edit config/suppressions.toml instead", "vulnerabilities:"]
    openvex = {"@context": "https://openvex.dev/ns/v0.2.0", "@id": f"https://secbench.local/vex/{today.isoformat()}",
               "author": "secbench", "timestamp": f"{today.isoformat()}T00:00:00Z", "version": 1, "statements": []}
    cdx_vex = {"bomFormat": "CycloneDX", "specVersion": "1.5", "version": 1, "vulnerabilities": []}
    gitleaks_lines, opengrep_paths, zap_lines = [], [], []

    for e in active:
        m = e.get("match", {})
        tool = e.get("tool")
        ovx, cdx_state = VEX_STATUS[e["status"]]
        note = f"{e['id']} {e['owner']} expires={e['expires']} :: {e['justification']}"
        if "vuln_id" in m and tool in ("trivy", "dependency-track", "*"):
            trivy_lines += [f"  - id: {m['vuln_id']}", f"    expired_at: {e['expires']}", f"    statement: {json.dumps(note)}"]
            if "purl" in m:
                trivy_lines += [f"    purls:", f"      - {json.dumps(m['purl'])}"]
            stmt = {"vulnerability": {"name": m["vuln_id"]}, "status": ovx, "justification": "vulnerable_code_not_in_execute_path"
                    if e["status"] == "not_affected" else None, "impact_statement": note}
            if "purl" in m:
                stmt["products"] = [{"@id": m["purl"]}]
            openvex["statements"].append({k: v for k, v in stmt.items() if v is not None})
            cdx_vex["vulnerabilities"].append({
                "id": m["vuln_id"],
                "analysis": {k: v for k, v in {
                    "state": cdx_state,
                    "justification": "code_not_reachable" if e["status"] == "not_affected" else None,
                    "response": ["will_not_fix"] if e["status"] == "accepted_risk" else None,
                    "detail": note}.items() if v is not None},
                **({"affects": [{"ref": m["purl"]}]} if "purl" in m else {}),
            })
        if tool == "gitleaks" and "fingerprint" in m:
            gitleaks_lines.append(m["fingerprint"])
        if tool == "opengrep" and set(m) == {"path"}:
            opengrep_paths.append(m["path"])
        if tool == "zap" and "zap_rule" in m:
            zap_lines.append(f"{m['zap_rule']}\tIGNORE\t({e['id']} {e['owner']} until {e['expires']})")

    if len(trivy_lines) == 2:
        trivy_lines.append("  []")
    (out_dir / ".trivyignore.yaml").write_text("\n".join(trivy_lines) + "\n")
    (out_dir / "vex.openvex.json").write_text(json.dumps(openvex, indent=2) + "\n")
    (out_dir / "vex.cdx.json").write_text(json.dumps(cdx_vex, indent=2) + "\n")
    (out_dir / ".gitleaksignore").write_text("\n".join(gitleaks_lines) + ("\n" if gitleaks_lines else ""))
    (out_dir / "opengrep-excludes.txt").write_text("\n".join(opengrep_paths) + ("\n" if opengrep_paths else ""))
    (out_dir / "zap-ignore.conf").write_text("\n".join(zap_lines) + ("\n" if zap_lines else ""))
    return active


if __name__ == "__main__":
    src = Path(sys.argv[1]); dst = Path(sys.argv[2])
    act = generate(src, dst)
    print(f"{len(act)} active suppression(s) → {dst}")
