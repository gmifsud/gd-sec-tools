#!/usr/bin/env bash
# pin-images.sh — the ONLY mutator of images.lock.
# Reads images.src (key=image:tag | key=build:<dir>), resolves immutable digests, pulls them, writes images.lock
# and management-plane/images.env. Review the diff of images.lock in a PR before merging.
set -euo pipefail
cd "$(dirname "$0")/.."

SRC=images.src
LOCK=images.lock
MP_ENV=management-plane/images.env
TMP_LOCK=$(mktemp); TMP_ENV=$(mktemp)
trap 'rm -f "$TMP_LOCK" "$TMP_ENV"' EXIT

echo "# images.lock — GENERATED by scripts/pin-images.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). Do not edit by hand." > "$TMP_LOCK"
echo "# source: images.src" >> "$TMP_LOCK"
echo "# management-plane/images.env — GENERATED by scripts/pin-images.sh" > "$TMP_ENV"

resolve_registry() {   # $1=image:tag → prints image@sha256:…
  local ref="$1" digest
  # buildx imagetools gives the manifest-list digest (multi-arch safe) without pulling
  digest=$(docker buildx imagetools inspect "$ref" --format '{{json .Manifest}}' 2>/dev/null | python3 -c 'import sys,json; print(json.load(sys.stdin)["digest"])' 2>/dev/null || true)
  if [[ -z "$digest" ]]; then
    docker pull -q "$ref" >/dev/null
    digest=$(docker image inspect "$ref" --format '{{index .RepoDigests 0}}' | sed 's/.*@//')
  fi
  echo "${ref%%:*}@${digest}"
}

base_digest() {        # pin the Dockerfile base image too
  resolve_registry "debian:bookworm-slim"
}

while IFS='=' read -r key val; do
  [[ -z "$key" || "$key" =~ ^# ]] && continue
  key=$(echo "$key" | xargs); val=$(echo "$val" | xargs)
  if [[ "$val" == build:* ]]; then
    dir="${val#build:}"
    base=$(base_digest)
    echo "building $key from $dir (base $base)" >&2
    iid=$(docker build -q --build-arg "BASE_IMAGE=$base" -t "secbench/$key:pinned" "$dir")
    # local builds have no RepoDigest; the image ID (sha256:<config digest>) is the immutable handle
    echo "$key=$iid" >> "$TMP_LOCK"
  else
    pinned=$(resolve_registry "$val")
    echo "pulling $pinned" >&2
    docker pull -q "$pinned" >/dev/null
    echo "$key=$pinned" >> "$TMP_LOCK"
    envkey="IMAGE_$(echo "$key" | tr 'a-z-' 'A-Z_')"
    echo "$envkey=$pinned" >> "$TMP_ENV"
  fi
done < "$SRC"

mv "$TMP_LOCK" "$LOCK"; mkdir -p management-plane; mv "$TMP_ENV" "$MP_ENV"
echo "wrote $LOCK and $MP_ENV:" >&2
cat "$LOCK"
